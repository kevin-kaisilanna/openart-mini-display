class ST7789:
    """1.54寸 240x240 ST7789 驱动（MicroPython for OpenART Mini）"""

    def __init__(self, spi, cs, dc, rst, blk=None, width=240, height=240):
        self.spi = spi
        self.cs = cs
        self.dc = dc
        self.rst = rst
        self.blk = blk
        self.width = width
        self.height = height
        self._init()
        if self.blk:
            self.blk.value(1)   # 开背光

    # ---------- 基础 SPI 通信 ----------
    def _write_cmd(self, cmd):
        self.cs.value(0)
        self.dc.value(0)        # 命令
        self.spi.write(bytes([cmd]))
        self.cs.value(1)

    def _write_data(self, data):
        self.cs.value(0)
        self.dc.value(1)        # 数据
        if isinstance(data, int):
            self.spi.write(bytes([data]))
        elif isinstance(data, (bytes, bytearray)):
            self.spi.write(data)
        self.cs.value(1)

    def _write_data16(self, data):
        """发送16位数据（RGB565），高字节在前"""
        self._write_data((data >> 8) & 0xFF)
        self._write_data(data & 0xFF)

    # ---------- 初始化序列 ----------
    def _init(self):
        # 硬件复位
        self.rst.value(0)
        time.sleep_ms(10)
        self.rst.value(1)
        time.sleep_ms(120)

        # 退出睡眠
        self._write_cmd(0x11)
        time.sleep_ms(120)

        # 颜色模式 16位
        self._write_cmd(0x3A)
        self._write_data(0x05)

        # 内存访问控制（方向）0x00: 竖屏，0xC0: 横屏，此处采用竖屏
        self._write_cmd(0x36)
        self._write_data(0x00)

        # 其他初始化参数（直接从STM32代码移植）
        self._write_cmd(0xB2)
        self._write_data(0x0C)
        self._write_data(0x0C)
        self._write_data(0x00)
        self._write_data(0x33)
        self._write_data(0x33)

        self._write_cmd(0xB7)
        self._write_data(0x35)

        self._write_cmd(0xBB)
        self._write_data(0x32)      # Vcom=1.35V

        self._write_cmd(0xC2)
        self._write_data(0x01)

        self._write_cmd(0xC3)
        self._write_data(0x15)      # GVDD=4.8V

        self._write_cmd(0xC4)
        self._write_data(0x20)      # VDV, 0x20:0v

        self._write_cmd(0xC6)
        self._write_data(0x0F)      # 60Hz

        self._write_cmd(0xD0)
        self._write_data(0xA4)
        self._write_data(0xA1)

        # 正负伽马校正
        self._write_cmd(0xE0)
        gamma_pos = bytes([0xD0, 0x08, 0x0E, 0x09, 0x09, 0x05, 0x31, 0x33,
                           0x48, 0x17, 0x14, 0x15, 0x31, 0x34])
        for b in gamma_pos:
            self._write_data(b)

        self._write_cmd(0xE1)
        gamma_neg = bytes([0xD0, 0x08, 0x0E, 0x09, 0x09, 0x15, 0x31, 0x33,
                           0x48, 0x17, 0x14, 0x15, 0x31, 0x34])
        for b in gamma_neg:
            self._write_data(b)

        self._write_cmd(0x21)       # 显示反相（可选，此处保留）
        self._write_cmd(0x29)       # 开启显示

    # ---------- 基础绘图函数 ----------
    def set_window(self, x0, y0, x1, y1):
        """设置显示区域（包含起点和终点）"""
        self._write_cmd(0x2A)       # 列地址
        self._write_data16(x0)
        self._write_data16(x1)
        self._write_cmd(0x2B)       # 行地址
        self._write_data16(y0)
        self._write_data16(y1)
        self._write_cmd(0x2C)       # 准备写入像素

    def fill(self, color=0xFFFF):
        """全屏填充颜色（16位RGB565）"""
        self.set_window(0, 0, self.width-1, self.height-1)
        # 构造全屏颜色数据（内存较大，240*240*2=115200字节，通常可行）
        pixel_count = self.width * self.height
        color_high = (color >> 8) & 0xFF
        color_low = color & 0xFF
        buf = bytearray(pixel_count * 2)
        for i in range(pixel_count):
            buf[2*i] = color_high
            buf[2*i+1] = color_low
        self._write_data(buf)

    def pixel(self, x, y, color):
        """画一个点"""
        self.set_window(x, y, x, y)
        self._write_data16(color)

    def image(self, x0, y0, x1, y1, data):
        """
        在指定区域显示图像数据（RGB565格式，数据为bytes或bytearray）。
        注意：data长度必须等于 (x1-x0+1)*(y1-y0+1)*2。
        """
        self.set_window(x0, y0, x1, y1)
        # 如果是 bytearray，就地交换字节序（小端 -> 大端）
        if isinstance(data, bytearray):
            for i in range(0, len(data), 2):
                data[i], data[i+1] = data[i+1], data[i]
        self._write_data(data)

